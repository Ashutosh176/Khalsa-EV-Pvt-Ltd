-- Postgres treats NULLs as distinct in a plain unique index, so a
-- compound @@unique([warehouseId, productId, variantId]) would not
-- stop two rows for the same warehouse+product when variantId is
-- NULL (and likewise for warehouse+variant when productId is NULL).
-- These partial unique indexes close that gap and are what actually
-- prevents duplicate stock rows / overselling races (Section 16).
CREATE UNIQUE INDEX "Inventory_warehouse_product_unique"
  ON "Inventory"("warehouseId", "productId")
  WHERE "variantId" IS NULL;

CREATE UNIQUE INDEX "Inventory_warehouse_variant_unique"
  ON "Inventory"("warehouseId", "variantId")
  WHERE "productId" IS NULL;

